"""文书生成提示词与格式规范（任务拆解 9.4.1）。

与 :mod:`app.ai.prompts`（问答）分开写，因为两者约束的**方向相反**：

- 问答要求「只用参考资料、没资料就说不知道」，越保守越好；
- 文书要求「按案件事实把骨架填满」，模型必须在信息缺失时**留下占位符**
  而不是含糊带过——起诉状里一句"原告信息略"就等于废纸。

所以这里的核心指令是：结构不能少、事实不能编、缺什么就用
``【待补充：xxx】`` 标出来，让律师一眼看到要补哪里。

每种文书的 ``outline`` 取自《民事诉讼法》第一百二十二条关于起诉状应记明
事项的规定、律师业务常用格式，以及法院立案窗口的实际要求；``rules`` 是
这一类文书最容易出错的地方（例如授权委托书笼统写"全权代理"，法律上不
产生特别授权效力）。
"""

