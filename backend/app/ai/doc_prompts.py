_USER_TEMPLATE = """【文书类型】{label}（{doc_type}）

【案件信息】
{fields}

【案件事实】
{facts}

【文书中的当事人称谓】委托方写「{party_self}」，对方写「{party_other}」。

【文书格式要求】
结构与顺序：
{outline}

特殊要求：
{rules}
{template_block}{extra_block}
请直接输出这份{label}的正文（Markdown），不要任何前言或解释。"""


def get_spec(doc_type: str) -> DocSpec:
    """取文书规范，未知类型回退到 ``other``（schema 层已做白名单校验）。"""
    return DOC_SPECS.get(doc_type, DOC_SPECS["other"])


def _format_fields(fields: dict[str, str], missing: list[str]) -> str:
    """把案件字段拼成「- 键：值」清单，缺失项显式标出。"""
    lines: list[str] = []
    for key, value in fields.items():
        if value:
            lines.append(f"- {key}：{value}")
    for key in missing:
        lines.append(f"- {key}：{placeholder_for(key)}")
    return "\n".join(lines) if lines else "- （未提供任何案件字段，请全部使用占位符）"


def build_document_messages(
    *,
    doc_type: str,
    fields: dict[str, str],
    missing: list[str],
    facts: str,
    requirements: str | None = None,
    template_content: str | None = None,
) -> list[Message]:
    """组装文书生成的消息列表。

    :param fields: 已取到值的案件字段（中文键 → 值）
    :param missing: 缺失的必备字段名，会在提示词里显式标注
    :param facts: 案件事实（来自案件描述或用户补充）
    :param requirements: 用户对本次生成的额外要求（语气、篇幅、侧重等）
    :param template_content: 引用模板时的格式骨架（``{变量}`` 未替换部分由模型
        按占位符规则处理）
    """
    spec = get_spec(doc_type)

    outline = "\n".join(f"{i}) {item}" for i, item in enumerate(spec.outline, 1))
    rules = "\n".join(f"- {item}" for item in spec.rules)

    template_block = ""
    if template_content and template_content.strip():
        template_block = (
            "\n【参考模板骨架】\n"
            "下列模板仅作结构与措辞参考。模板中未替换的 `{变量}` 表示该项信息"
            "未提供，请按第 4 条改写为 `【待补充：变量名】`，不要原样保留花括号。\n\n"
            f"{template_content.strip()}\n"
        )

    extra_block = ""
    if requirements and requirements.strip():
        extra_block = f"\n【本次额外要求】\n{requirements.strip()}\n"

    user_content = _USER_TEMPLATE.format(
        label=spec.label,
        doc_type=doc_type,
        fields=_format_fields(fields, missing),
        facts=facts.strip(),
        party_self=spec.party_roles[0],
        party_other=spec.party_roles[1],
        outline=outline,
        rules=rules,
        template_block=template_block,
        extra_block=extra_block,
    )

    return [
        {"role": "system", "content": _SYSTEM_PROMPT.format(firm=settings.firm_name)},
        {"role": "user", "content": user_content},
    ]
